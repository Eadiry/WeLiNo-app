/**
 * Bundles the WebView reader's CSS + JS into a TS module so the reader works
 * on iOS.
 *
 * LNReader loads `assets/reader/{css,js}` from `file:///android_asset` at
 * runtime — an Android-only path. `plugins/withReaderAssets.js` only copies
 * them into the Android project, and nobody bundles them for iOS, so on iPhone
 * the reader page has no stylesheet and no scripts: it can't scroll, can't
 * toggle the toolbar, can't move between chapters, and ignores the safe area.
 *
 * The assets are tiny (~85 KB of CSS + JS), so instead of wiring them into the
 * iOS bundle we inline them into the generated document. Run this whenever the
 * upstream `assets/reader` sources change:
 *
 *   pnpm run generate:reader-assets
 *
 * The output is committed so a fresh checkout / `expo run:ios` works without
 * the extra step; CI regenerates it before prebuild to stay in sync.
 */
const fs = require('fs');
const path = require('path');

const READER_ROOT = path.join(__dirname, '..', 'assets', 'reader');
const OUT_FILE = path.join(
  __dirname,
  '..',
  'src',
  'screens',
  'reader',
  'utils',
  'readerAssets.ts',
);

// Load order mirrors the <link> / <script> tags WebViewReader used to emit.
const CSS_FILES = [
  'css/index.css',
  'css/pageReader.css',
  'css/toolWrapper.css',
  'css/tts.css',
];
const JS_FILES = [
  'js/polyfill-onscrollend.js',
  'js/icons.js',
  'js/van.js',
  'js/text-vibe.js',
  'js/core.js',
  'js/search.js',
  'js/index.js',
  'js/textRemover.js',
];

/** Stop an embedded `</script>` / `</style>` from closing the host tag early. */
const neutralizeClosers = str => str.replace(/<\/(script|style)/gi, '<\\/$1');

const read = rel => {
  const file = path.join(READER_ROOT, rel);
  if (!fs.existsSync(file)) {
    throw new Error(`Missing reader asset: ${rel}`);
  }
  return neutralizeClosers(fs.readFileSync(file, 'utf8').trim());
};

const css = CSS_FILES.map(read).join('\n\n');
const scripts = JS_FILES.map(read);

const banner =
  `// AUTO-GENERATED by scripts/generate-reader-assets.cjs — do not edit.\n` +
  `// Run \`pnpm run generate:reader-assets\` after changing assets/reader.\n` +
  `/* eslint-disable */\n` +
  `// prettier-ignore\n`;

const body =
  `export const READER_CSS: string = ${JSON.stringify(css)};\n\n` +
  `export const READER_SCRIPTS: readonly string[] = [\n` +
  scripts.map(s => `  ${JSON.stringify(s)},`).join('\n') +
  `\n];\n`;

fs.writeFileSync(OUT_FILE, banner + '\n' + body);

const kb = n => `${(n / 1024).toFixed(1)} KB`;
console.log(
  `reader assets -> ${path.relative(process.cwd(), OUT_FILE)}  ` +
    `(css ${kb(css.length)}, js ${kb(scripts.join('').length)})`,
);
